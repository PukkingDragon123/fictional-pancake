  function build(name) {
    const def = DEF[name];
    if (!def) return null;
    const fn = typeof def === 'function' ? def : def.draw;
    const res = typeof def === 'function' ? SZ : (def.res || SZ);
    const { c, g } = Art.cv(res, res);
    fn({
      g,
      R: (x, y, w, h, col) => Art.rect(g, x, y, w, h, col),
      E: (x, y, rx, ry, col) => Art.ell(g, x, y, rx, ry, col),
      L: (x0, y0, x1, y1, col, t) => Art.line(g, x0, y0, x1, y1, col, t || 1),
      P: (pts, col) => Art.poly(g, pts, col),
      LB: (x0, y0, x1, y1, w0, w1, col) => Art.limb(g, x0, y0, x1, y1, w0, w1, col),
    });
    Art.outline(c, '#0a0810', 1);           // the same black line as everything else
    return c;
  }
  function canvas(name) {
    let c = canvases.get(name);
    if (c === undefined) { c = build(name); canvases.set(name, c); }
    return c;
  }
  function url(name) {
    let u = urls.get(name);
    if (u !== undefined) return u;
    const c = canvas(name);
    if (!c) { urls.set(name, ''); return ''; }
    const { c: big, g } = Art.cv(c.width * 2, c.height * 2);
    g.imageSmoothingEnabled = false;
    g.drawImage(c, 0, 0, c.width * 2, c.height * 2);
    u = big.toDataURL();
    urls.set(name, u);
    return u;
  }
  function img(name, cls = '', extra = '') { return `<img class="ico ${cls}" src="${url(name)}" alt="" ${extra}>`; }
  // `scale` is measured against the 16px grid so callers keep their sizes.
  function blit(g, name, x, y, scale = 1) {
    const c = canvas(name);
    if (c) g.drawImage(c, Math.round(x), Math.round(y), SZ * scale, SZ * scale);
  }
  return { url, img, blit, canvas, names: () => Object.keys(DEF) };
